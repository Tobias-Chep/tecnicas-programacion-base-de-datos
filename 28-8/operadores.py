numero1 = -4

numero2 = -2

# Suma de números

suma = numero1 + numero2
print("La suma de", numero1, "más", numero2, "es igual a", suma)

# Resta de números

resta = numero1 - numero2
print("La resta de", numero1, "menos", numero2, "es igual a", resta)

## Multiplicacion de números

multiplicacion = numero1 * numero2
print("La multiplicación de", numero1, "por", numero2, "es igual a", multiplicacion)

## División de números

division = numero1 / numero2
print("La división de", numero1, "dividido", numero2, "es igual a", division)

## División entera

divisionEntera = numero1 // numero2
print("La división entera de", numero1, "dividido", numero2, "es igual a", divisionEntera)
print("El tipo de dato de la variable 'división' es", type(division))

## Resto

resto = numero1 % numero2
print("El resto de", numero1, "dividido", numero2, "es igual a", resto)

## Potencia

potencia = numero1 ** numero2
print("La potencia de", numero1, "elevado a", numero2, "es igual a", potencia)

## Raíz

raiz = numero1 ** (1/numero2)

print(type(raiz))
print("La raíz de", numero1, "por", numero2, "es igual a", raiz)
